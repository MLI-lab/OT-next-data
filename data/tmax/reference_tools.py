"""Declare immutable reference programs, separately from submitted task code.

Programs generated by initialization are captured privately before the agent,
then restored from /tests. Their per-trial state never enters a shared cache.
"""
import ast
import hashlib
import json
from pathlib import Path, PurePosixPath
from functools import lru_cache
import re
import shlex

from harbor_patches.verifier_assets import FORMAT, TARGET, child_environment


def source_identity(files):
    value = hashlib.sha256()
    for name in ('tests/test_final_state.py', 'setup_files/task_install.sh', 'instruction.md'):
        value.update(name.encode() + b'\0' + files.get(name, (b'',))[0] + b'\0')
    return value.hexdigest()


@lru_cache(maxsize=1)
def reviewed_programs():
    return json.loads(Path(__file__).with_name('reference_program_roles.json').read_text())['records']


def imports(source):
    try:
        tree = ast.parse(source)
    except (SyntaxError, UnicodeDecodeError):
        return set()
    return {a.name.split('.')[0] for n in ast.walk(tree) if isinstance(n, ast.Import) for a in n.names} | {
        n.module.split('.')[0] for n in ast.walk(tree) if isinstance(n, ast.ImportFrom) and n.module and not n.level}


def task_owned(instruction, path):
    """Explicit write/repair targets stay under the agent's control."""
    for parent in PurePosixPath(path).parents:
        if len(parent.parts) >= 3 and task_owned(instruction, str(parent)):
            return True
    name = re.escape(path)
    boundary = r'(?=$|[^A-Za-z0-9_./+-]|[.](?:\s|$))'
    verbs = r'(?:write|create|implement|repair|fix|modify|restore|rebuild|compile)'
    # Require the path to be the direct write target. "Write a replacement
    # whose output matches /app/oracle" describes an immutable reference.
    words = r'(?:a|an|the|your|new|existing|replacement|optimized|pure|executable|standalone|Python|Python3|Bash|C\+\+|Go|script|file|program|binary|package|module|library|implementation|to|at|in)'
    for line in re.split(r'(?<=[.!?])\s+|\n', instruction):
        if path not in line or re.search(r'(?i)do not|don.t|must not|never', line):
            continue
        if re.search(r'(?i)\b' + verbs + r'\s+(?:' + words + r'\s+){0,8}[`\"\']*' + name + boundary, line):
            return True
        if re.search(r'(?i)your (?:final )?(?:solution|script|program) (?:must|should) be '
                     r'[^.;\n]{0,60}?(?:located |saved |written )?(?:at|in)\s+[`\"\']*' + name + boundary, line):
            return True
    return False


def supplied_sources(files):
    """Read literal source files without executing initialization or its generators."""
    sources = {}
    for name, (content, _) in files.items():
        prefix = next((p for p in ('environment/_fixtures/', 'setup_files/fixtures/') if name.startswith(p)), None)
        if prefix and name.endswith(('.py', '.sh')):
            try:
                sources['/' + name.removeprefix(prefix)] = content.decode()
            except UnicodeDecodeError:
                pass
    setup = '\n'.join(files.get(name, (b'',))[0].decode() for name in (
        'environment/base_install.sh', 'environment/post_install.sh', 'setup_files/task_install.sh'))
    lines = setup.splitlines(); i = 0; cwd = '/'
    while i < len(lines):
        line = lines[i].strip(); i += 1
        here = re.search(r'<<-?\s*([\"\']?)([A-Za-z_][A-Za-z_0-9]*)\1', line)
        if here:
            body = []
            while i < len(lines) and lines[i].strip() != here[2]:
                body.append(lines[i]); i += 1
            i += 1
            dest = re.search(r'(?<![<>])>\s*([\"\']?)([^\s\"\']+)\1', line)
            if dest and line.startswith('cat ') and '$' not in dest[2]:
                target = str(PurePosixPath(cwd) / dest[2])
                sources[target] = '\n'.join(body) + '\n'
            # Literal Python-generated scripts are still source declarations;
            # inspect their AST without executing initialization or random draws.
            try:
                tree = ast.parse('\n'.join(body))
            except SyntaxError:
                tree = None
            if tree is not None:
                constants = {target.id: node.value.value for node in ast.walk(tree)
                             if isinstance(node, ast.Assign) and isinstance(node.value, ast.Constant)
                             and isinstance(node.value.value, str) for target in node.targets
                             if isinstance(target, ast.Name)}
                for node in ast.walk(tree):
                    if not isinstance(node, ast.With) or len(node.items) != 1:
                        continue
                    item = node.items[0]; call = item.context_expr
                    if not (isinstance(call, ast.Call) and isinstance(call.func, ast.Name) and call.func.id == 'open'
                            and call.args and isinstance(call.args[0], ast.Constant)
                            and isinstance(call.args[0].value, str) and call.args[0].value.startswith('/')
                            and isinstance(item.optional_vars, ast.Name)):
                        continue
                    for statement in node.body:
                        value = statement.value if isinstance(statement, ast.Expr) else None
                        if (isinstance(value, ast.Call) and isinstance(value.func, ast.Attribute)
                                and isinstance(value.func.value, ast.Name) and value.func.value.id == item.optional_vars.id
                                and value.func.attr == 'write' and len(value.args) == 1):
                            arg = value.args[0]
                            content = constants.get(arg.id) if isinstance(arg, ast.Name) else arg.value if isinstance(arg, ast.Constant) else None
                            if isinstance(content, str):
                                sources[call.args[0].value] = content
            continue
        try:
            args = shlex.split(line)
        except ValueError:
            continue
        if args[:1] == ['cd'] and len(args) > 1 and args[1].startswith('/'):
            cwd = args[1]
        if args[:1] in (['cp'], ['mv']) and len(args) == 3:
            source, target = (str(PurePosixPath(cwd) / p) for p in args[1:])
            if source in sources:
                sources[target] = sources[source]
    return sources


def plan(files):
    test = files['tests/test_final_state.py'][0].decode()
    instruction = files['instruction.md'][0].decode()
    tree = ast.parse(test); candidates = set(); constants = {}; directories = set()
    if 'subprocess' not in imports(test) and not re.search(r'os\.(?:system|popen|exec)', test):
        return dict(paths=[], imports=[], exceptions={}, unknown_sources=[])
    for node in ast.walk(tree):
        if isinstance(node, ast.Assign) and isinstance(node.value, ast.Constant) and isinstance(node.value.value, str):
            for target in node.targets:
                if isinstance(target, ast.Name):
                    constants[target.id] = node.value.value
                    if re.search(r'(?:^|_)(?:dir|directory|root)$', target.id, re.I):
                        directories.add(node.value.value)
                    if re.search(r'oracle|reference|^ref_', target.id, re.I):
                        candidates.add(node.value.value)
    # Also cover literal oracle paths passed directly to subprocess helpers.
    candidates.update(node.value for node in ast.walk(tree) if isinstance(node, ast.Constant)
                      and isinstance(node.value, str) and 'oracle' in node.value.lower())
    for node in ast.walk(tree):
        if isinstance(node, ast.Call) and node.args and ast.unparse(node.func) in ('os.path.isdir', 'os.makedirs', 'os.mkdir'):
            arg = node.args[0]
            value = constants.get(arg.id) if isinstance(arg, ast.Name) else arg.value if isinstance(arg, ast.Constant) else None
            if isinstance(value, str):
                directories.add(value)
    candidates -= directories
    reviewed = reviewed_programs().get(source_identity(files), {}).get('programs', [])
    launchers = {p['path'] for p in reviewed if p['role'] == 'task_launcher'}
    candidates.update(p['path'] for p in reviewed if p['role'] in ('reference', 'task_launcher'))
    paths, exceptions = set(), {p['path']: p['reason'] for p in reviewed if p['role'] == 'task_code'}
    for path in candidates:
        if path in exceptions:
            continue
        if not path.startswith(('/app/', '/opt/', '/home/')) or any(c.isspace() for c in path):
            continue
        if PurePosixPath(path).suffix.lower() not in ('', '.py', '.pyc', '.sh', '.bin', '.elf', '.exe'):
            continue
        if task_owned(instruction, path):
            exceptions[path] = 'The instruction explicitly asks the agent to create or change this program.'
        else:
            paths.add(path)
    # This task asks for restoring the reference itself from a lost archive.
    # Its original setup documents that /app/oracle_parser appears only after
    # the agent restores /home/user/restored_data/oracle_parser.
    setup = files.get('setup_files/task_install.sh', (b'',))[0].decode()
    if 'cp /home/user/restored_data/oracle_parser /app/oracle_parser' in setup:
        for path in ('/app/oracle_parser', '/home/user/restored_data/oracle_parser'):
            if path in paths:
                paths.remove(path)
                exceptions[path] = 'Reference recovery is part of the requested submitted filesystem state.'
    if not paths:
        return dict(paths=[], imports=[], exceptions=exceptions, unknown_sources=[])
    sources = supplied_sources(files)
    paths = {p for p in paths if p in sources or not any(s.startswith(p + '/') for s in sources)}
    pending = list(paths); modules = set(); local_modules = set()
    while pending:
        path = pending.pop()
        if path in launchers:
            continue  # The service and its imports are the code under test.
        source = sources.get(path)
        if source is None:
            continue
        modules.update(imports(source))
        dependencies = {p for p in re.findall(r'/(?:app|opt|home)/[A-Za-z0-9_./+-]+\.(?:py|sh)', source)
                        if p in sources and p not in exceptions}
        roots = [str(PurePosixPath(path).parent)]
        roots += re.findall(r"sys\.path\.(?:insert\(\s*\d+\s*,|append\()\s*['\"](/[^'\"]+)['\"]", source)
        for module in imports(source):
            found = False
            for root in roots:
                package = str(PurePosixPath(root) / module)
                if package + '.py' in sources:
                    dependencies.add(package + '.py'); found = True
                elif package + '/__init__.py' in sources:
                    dependencies.update(p for p in sources if p.startswith(package + '/') and p.endswith('.py'))
                    found = True
                if found:
                    local_modules.add(module)
                    break
            if not found and module.endswith('_pb2'):
                dependencies.add(str(PurePosixPath(path).parent / (module + '.py')))
                local_modules.add(module); modules.add('google')
        for dependency in dependencies - paths:
            if dependency not in exceptions and not task_owned(instruction, dependency):
                paths.add(dependency); pending.append(dependency)
    return dict(paths=sorted(paths), task_launchers=sorted(launchers & paths),
                imports=sorted(modules - local_modules), exceptions=exceptions,
                unknown_sources=sorted(p for p in paths if p not in sources))




def apply(files, planned, *, task_paths=(), task_python=None):
    if not planned['paths']:
        return False
    config = dict(format=FORMAT, paths=planned['paths'], task_paths=list(task_paths))
    launchers = planned.get('task_launchers', [])
    if launchers:
        config['task_launchers'] = launchers
    if task_python:
        config['task_python'] = task_python
    files['tests/ot-verifier-assets.json'] = (json.dumps(config, sort_keys=True).encode() + b'\n', 0o644)
    setup, mode = files['tests/setup.sh']
    commands = '\n# Restore private pre-agent reference files supplied by the controller.\n'
    commands += 'test -f ' + TARGET + '/manifest.json || { echo "Missing trusted verifier asset capture" >&2; exit 1; }\n'
    for path in planned['paths']:
        source = shlex.quote(TARGET + path); destination = shlex.quote(path)
        commands += (f'if [ -f {source} ]; then\n'
                     f'  mkdir -p {shlex.quote(str(PurePosixPath(path).parent))}\n'
                     f'  cp -p --remove-destination {source} {destination}\n'
                     f'else\n  rm -f -- {destination}\nfi\n')
    files['tests/setup.sh'] = (setup + commands.encode(), mode)
    conftest, mode = files.get('tests/conftest.py', (b'', 0o644))
    files['tests/conftest.py'] = (conftest + child_environment(set(planned['paths']) - set(launchers)).encode(), mode)
    return True
